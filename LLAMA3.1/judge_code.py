rec_b  = tp_b / (tp_b + fn_b) if (tp_b + fn_b) > 0 else 0
f1_b   = 2 * prec_b * rec_b / (prec_b + rec_b) if (prec_b + rec_b) > 0 else 0
acc_b  = (tp_b + tn_b) / total_j if total_j > 0 else 0
print(f'\n  Accuracy  : {acc_b:.3f}')
print(f'  Precision : {prec_b:.3f}')
print(f'  Recall    : {rec_b:.3f}')
print(f'  F1-score  : {f1_b:.3f}')

# ── Comparaison finale ────────────────────────────────────────────────────────
print(f'\n🏆 4. COMPARAISON FINALE')
print(sep2)
