def groq_judge_call(messages: list, system: str,
                    temperature: float = 0.0,
                    max_retries: int = 5,
                    retry_wait: int = 30,
                    max_tokens: int = 1200) -> str:
    extra = {}
    if JUDGE_MODEL_ID in ("qwen/qwen3-32b", "qwen-qwq-32b"):
        extra["reasoning_format"] = "hidden"
    elif JUDGE_MODEL_ID in ("openai/gpt-oss-20b", "openai/gpt-oss-120b"):
        extra["reasoning_effort"] = "medium"

    for attempt in range(max_retries):
        try:
            completion = client.chat.completions.create(
                model=JUDGE_MODEL_ID,
                messages=[{"role": "system", "content": system}] + messages,
                temperature=temperature,
                max_tokens=max_tokens,
                stream=False,
                **extra,
            )
            return completion.choices[0].message.content
        except Exception as e:
            msg = str(e).lower()
            status_code = getattr(e, 'status_code', None)
            if status_code == 413 or '413' in msg or 'request too large' in msg:
                raise RuntimeError(
                    f"Requête trop grande (413) — réduis le texte. Détail: {str(e)[:200]}"
                ) from None
            elif any(k in msg for k in ("rate_limit", "rate limit", "too many requests", "429")):
                wait = retry_wait * (attempt + 1)
                print(f"    ⏳ Rate-limit — attente {wait}s (tentative {attempt+1}/{max_retries})...")
                time.sleep(wait)
            else:
                raise
    raise RuntimeError(f"Rate-limit persistant après {max_retries} tentatives.")

