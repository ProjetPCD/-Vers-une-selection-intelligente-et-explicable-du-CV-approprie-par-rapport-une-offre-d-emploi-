def run_judge(job_text, cv_text, baseline_result, pipeline_result,
              job_idx, cv_col):

    score_a = baseline_result.get('score', 0)

    # Normalise le score pipeline (combo_v6_final) sur 100
    combo_raw = pipeline_result.get('combo_v6_final', 0) or 0
    score_b = round(float(combo_raw) * 100) if float(combo_raw) <= 1 else round(float(combo_raw))

    system = """You are an expert HR evaluator and impartial judge between two CV-job matching systems.

## Your Task
1. Read the job description and the CV carefully.
2. Decide the ground truth: is this CV a genuine match for this job? (1 = match, 0 = no match)
3. Derive each system's binary prediction from its score (>= threshold → 1, else → 0).
4. Classify each prediction as TP, TN, FP, or FN against your ground truth.

## Reasoning rules
- A match requires the candidate to cover the majority of the required skills and experience level.
- Be strict: a partial profile or missing key requirements = no match.
- Justify your ground truth decision in 2-3 sentences.

## Output format (strict JSON, no extra text)
{
  "ground_truth": 1 or 0,
  "reasoning": "...",
  "system_a_prediction": 1 or 0,
  "system_b_prediction": 1 or 0,
  "system_a_outcome": "TP" or "TN" or "FP" or "FN",
  "system_b_outcome": "TP" or "TN" or "FP" or "FN"
}"""

    user_content = f"""## Job Description
{str(job_text)[:900] if job_text else "Non disponible"}

## CV
{str(cv_text)[:900] if cv_text else "Non disponible"}

## System Scores
- System A (Baseline): {score_a}/100
- System B (Pipeline): {score_b}/100
- Decision threshold: {THRESHOLD}/100 (score >= threshold → predicted as "match")"""

    raw = groq_judge_call(
        messages=[{"role": "user", "content": user_content}],
        system=system,
        temperature=0.0,
        max_tokens=400
    )

    raw = raw.replace('```json', '').replace('```', '').strip()
    start = raw.find('{')
    end   = raw.rfind('}')

    if start == -1 or end == -1 or end <= start:
        raise ValueError(f"JSON incomplet ({len(raw)} chars): {raw[:300]}")

    try:
        parsed = json.loads(raw[start:end+1])
    except json.JSONDecodeError as e:
        raise ValueError(f"JSON malformé à pos {e.pos}: {raw[start:end+1][:300]}")

    parsed['job_idx'] = job_idx
    parsed['cv_col']  = cv_col
    return parsed


