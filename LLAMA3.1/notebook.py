# ── SharedLLM thread-safe ────────────────────────────────────
_llm_lock  = threading.Lock()
_llm_stats = {"calls": 0, "total_s": 0.0}

class SharedLLM:
    def __init__(self):
        self._llm  = pipeline_mod.CvLLM()
        self.model = self._llm.model
        self.client = self

    def generate(self, prompt, system_prompt="", temperature=0.1,
                 max_tokens=800, is_json=True, max_retries=2):
        with _llm_lock:
            t0  = time.time()
            res = self._llm.generate(prompt, system_prompt, temperature,
                                     max_tokens, is_json, max_retries)
            _llm_stats["calls"]   += 1
            _llm_stats["total_s"] += time.time() - t0
            return res

    def chat_completion(self, messages, temperature=0.1, max_tokens=300):
        with _llm_lock:
            t0  = time.time()
            res = self._llm.client.chat_completion(messages, temperature, max_tokens)
            _llm_stats["calls"]   += 1
            _llm_stats["total_s"] += time.time() - t0
            return res

shared_llm = SharedLLM()
print(f"✅ SharedLLM ({shared_llm.model}) | {NUM_AGENTS} agent(s)\n")

