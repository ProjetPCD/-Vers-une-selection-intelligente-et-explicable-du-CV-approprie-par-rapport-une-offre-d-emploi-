print_lock = threading.Lock()

def run_agent(agent_id: int, task: tuple) -> dict:
    job_id, cv_col, cv_text, jd_text, graph_data = task
    pair_key = f"{job_id}_{cv_col}"
    result   = {"agent_id": agent_id, "pair_key": pair_key,
                "success": False, "verdict": "N/A", "elapsed": 0}
    t0 = time.time()
    with print_lock:
        print(f"\n  [Agent {agent_id}] ▶ {pair_key}")
    try:
        audit = run_phase2_audit(job_data=graph_data, cv_text=cv_text,
                                  llm=shared_llm, job_id=job_id, cv_id=cv_col)
        if not audit or not audit.get("skill_instructions"):
            with print_lock: print(f"  [Agent {agent_id}] ❌ Phase 2 vide")
            return result
        with open(os.path.join(RESULTS_DIR, f"{pair_key}_phase2.json"), "w", encoding="utf-8") as f:
            json.dump(audit, f, indent=2, ensure_ascii=False)
        with print_lock:
            print(f"  [Agent {agent_id}] ✅ P2 — {len(audit.get('skill_instructions',{}))} skills")

        scored = run_phase3_scoring(audit, shared_llm)
        scored["scored_nodes"] = apply_exp_cert_bonus(
            scored_nodes=scored["scored_nodes"],
            skill_instructions=audit.get("skill_instructions", {}),
            exp_years=audit.get("exp_years", {}),
        )
        with open(os.path.join(RESULTS_DIR, f"{pair_key}_phase3.json"), "w", encoding="utf-8") as f:
            json.dump(scored, f, indent=2, ensure_ascii=False)
        mean = scored.get("metadata", {}).get("mean_score", "?")
        with print_lock:
            print(f"  [Agent {agent_id}] ✅ P3 — {len(scored.get('scored_nodes',{}))} scores | moy={mean}")

        audited = run_phase3_5_bias_audit(
            phase3_output=scored, graph_data=graph_data,
            job_desc=jd_text, cv_text=cv_text,
            label=pair_key, llm=shared_llm,
        )
        with open(os.path.join(BIAS_DIR, f"{pair_key}_audited.json"), "w", encoding="utf-8") as f:
            json.dump(audited, f, indent=2, ensure_ascii=False)
        b = audited.get("bias_summary", {})
        with print_lock:
            print(f"  [Agent {agent_id}] ✅ P3.5 — biais={b.get('nodes_with_bias',0)}/{b.get('nodes_audited',0)}")

        report = phase4_generate_report(
            job_id=job_id, cv_id=cv_col,
            graph_data=graph_data, phase3_data=audited,
        )
        with open(os.path.join(REPORTS_DIR, f"report_{pair_key}.json"), "w", encoding="utf-8") as f:
            json.dump(report, f, indent=2, ensure_ascii=False)

        verdict = report.get("overall_assessment", {}).get("verdict", "?")
        match   = report.get("overall_assessment", {}).get("match_pct", "?")
        elapsed = round(time.time() - t0, 1)
        result.update({"success": True, "verdict": verdict, "match_pct": match, "elapsed": elapsed})
        with print_lock:
            print(f"\n  [Agent {agent_id}] ✅ DONE {pair_key} | {verdict} ({match}%) | {elapsed}s")

    except Exception as exc:
        import traceback
        result["elapsed"] = round(time.time() - t0, 1)
        result["error"]   = str(exc)
        with print_lock:
            print(f"\n  [Agent {agent_id}] ❌ FAIL {pair_key} | {exc}")
            traceback.print_exc()
    return result

