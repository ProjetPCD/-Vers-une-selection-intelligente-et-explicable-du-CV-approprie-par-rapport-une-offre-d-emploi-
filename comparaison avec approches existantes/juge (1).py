def safe_json_parse(text):
    """Nettoie et parse un JSON retourné par le LLM."""
    text = re.sub(r'^```(?:json)?\s*|\s*```$', '', text.strip(), flags=re.MULTILINE)
    m = re.search(r'\{.*\}', text, re.DOTALL)
    if m:
        text = m.group()
    return json.loads(text)

def call_with_retry(messages, retries=RETRIES):
    for attempt in range(retries):
        try:
            raw = llm_call(messages)
            return safe_json_parse(raw)
        except json.JSONDecodeError as e:
            print(f"  JSONDecodeError (t{attempt+1}): {e}")
            time.sleep(2 ** attempt * SLEEP_API)
        except Exception as e:
            wait = 2 ** attempt * SLEEP_API
            print(f"  Erreur API (t{attempt+1}): {e} — attente {wait:.1f}s")
            time.sleep(wait)
    return None

