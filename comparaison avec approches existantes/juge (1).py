def load_reports(model_root):
    """Charge report_job_X_cv_Y.json depuis model_root/reports/"""
    reports_dir = Path(model_root) / "reports"
    data = {}
    if not reports_dir.exists():
        print(f"  ⚠ Dossier introuvable : {reports_dir}")
        return data
    for p in reports_dir.glob("report_job_*_cv_*.json"):
        m = re.match(r"report_(job_\w+)_(cv_\w+)\.json", p.name)
        if not m:
            continue
        jid, cid = m.group(1), m.group(2)
        try:
            with open(p, encoding="utf-8") as f:
                rep = json.load(f)
            data.setdefault(jid, {})[cid] = rep
        except Exception as e:
            print(f"  Erreur lecture {p.name}: {e}")
    return data

