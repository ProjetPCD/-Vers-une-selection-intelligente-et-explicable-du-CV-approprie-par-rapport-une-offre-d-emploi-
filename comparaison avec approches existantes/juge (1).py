class GroqKeyRotator:
    """Tourne automatiquement sur la clé suivante en cas de RateLimitError."""

    def __init__(self, keys):
        if not keys:
            raise ValueError("Aucune clé Groq fournie dans GROQ_API_KEYS.")
        self._keys   = keys
        self._idx    = 0
        self._lock   = threading.Lock()
        self._clients = {k: Groq(api_key=k) for k in keys}
        print(f"[KeyRotator] {len(keys)} clé(s) Groq chargée(s).")

    @property
    def current_key(self):
        return self._keys[self._idx]

    @property
    def client(self):
        return self._clients[self.current_key]

    def _rotate(self):
        with self._lock:
            next_idx = (self._idx + 1) % len(self._keys)
            if next_idx == self._idx:
                raise RuntimeError("[KeyRotator] Toutes les clés Groq sont épuisées !")
            self._idx = next_idx
            print(f"[KeyRotator] Bascule sur la clé #{self._idx + 1} (sur {len(self._keys)}).")

    def chat_completions_create(self, **kwargs):
        for attempt in range(len(self._keys)):
            try:
                return self.client.chat.completions.create(**kwargs)
            except RateLimitError as e:
                print(f"[KeyRotator] RateLimitError clé #{self._idx + 1}: {e}")
                self._rotate()
        raise RuntimeError("[KeyRotator] Toutes les clés Groq sont épuisées après rotation.")

