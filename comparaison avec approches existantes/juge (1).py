def evaluate_model_report(reference, model_report, jd_text, cv_text):
    """Évalue le rapport d'un modèle par rapport au rapport de référence."""

    rep_summary = {
        "verdict":        (model_report.get("overall_assessment") or {}).get("verdict"),
        "match_pct":      (model_report.get("overall_assessment") or {}).get("match_pct"),
        "confidence":     (model_report.get("overall_assessment") or {}).get("confidence", {}).get("confidence_score"),
        "final_scores":   model_report.get("final_scores"),
        "critical_gaps":  model_report.get("critical_gaps", [])[:6],
        "strengths":      (model_report.get("profile_summary") or {}).get("strengths", [])[:5],
        "critical_weaknesses": (model_report.get("profile_summary") or {}).get("critical_weaknesses", [])[:5],
        "rationale":      str(model_report.get("decision_rationale") or "")[:400],
        "key_metrics": {
            k: (v.get("value") if isinstance(v, dict) else v)
            for k, v in (model_report.get("advanced_metrics_v6") or {}).items()
            if k in ["node_matching_cosine","weighted_f1","gap_score","jaccard_nodes","missing_critical_penalty"]
        }
    }
    prompt = (
        f"## JD (extrait)\n{jd_text[:800]}\n\n"
        f"## CV (extrait)\n{cv_text[:800]}\n\n"
        f"## RAPPORT DE RÉFÉRENCE (vérité terrain)\n"
        f"{json.dumps(reference, ensure_ascii=False, indent=2)[:1800]}\n\n"
        f"## RAPPORT DU MODÈLE À ÉVALUER\n"
        f"{json.dumps(rep_summary, ensure_ascii=False, indent=2)[:1800]}\n\n"
        "## TÂCHE\n"
        "Compare le rapport du modèle avec la référence. Détecte :\n"
        "- Hallucinations (gaps ou forces inventés non présents dans le CV/JD)\n"
        "- Erreurs de verdict ou de match%\n"
        "- Incohérences internes des métriques\n"
        "- Gaps critiques manqués\n\n"
        f"## Schéma JSON attendu\n{json.dumps(EVAL_SCHEMA, ensure_ascii=False, indent=2)}"
    )
    return call_with_retry([
        {"role": "system", "content": JUDGE_SYSTEM},
        {"role": "user",   "content": prompt}
    ])

