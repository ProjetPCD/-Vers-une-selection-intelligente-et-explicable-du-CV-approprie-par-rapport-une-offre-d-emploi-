import numpy as np

SCORE_FIELDS = [
    "verdict_accuracy", "match_pct_accuracy",
    "hallucination_score", "reliability_score",
    "error_score", "overall"
]

def aggregate_judgments(all_judgments):
    agg = {}
    for pair_key, j in all_judgments.items():
        for model_name, eval_res in j.get("models", {}).items():
            if eval_res.get("skipped"):
                continue
            agg.setdefault(model_name, {f: [] for f in SCORE_FIELDS})
            for field in SCORE_FIELDS:
                val = eval_res.get(field)
                if isinstance(val, (int, float)):
                    agg[model_name][field].append(float(val))
    # Moyenne
    summary = {}
    for model_name, fields in agg.items():
        summary[model_name] = {
            f: round(float(np.mean(v)), 2) if v else None
            for f, v in fields.items()
        }
        summary[model_name]["n_evaluated"] = max(len(v) for v in fields.values()) if fields else 0
    return summary

