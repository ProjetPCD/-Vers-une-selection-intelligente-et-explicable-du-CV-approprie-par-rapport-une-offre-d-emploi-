"""## ═══ BLOC 12 — 🏆 Jugement Groq : Quel modèle est le plus réaliste ? ═══

Groq (LLaMA 3.3 70B) analyse les résultats des deux autres modèles et détermine lequel est le plus **fiable et réaliste**.
"""

import json

def build_comparison_pairs(df_all: pd.DataFrame, max_pairs: int = 5) -> list:
    """
    Construit des paires de comparaison pour les mêmes job_idx × cv_col
    évalués par plusieurs modèles.
    """
    pairs = []
    grouped = df_all.groupby(['job_idx','cv_col'])
    count = 0
    for (job_idx, cv_col), grp in grouped:
        if len(grp) >= 2:
            entry = {'job_idx': job_idx, 'cv_col': cv_col, 'evaluations': []}
            for _, row in grp.iterrows():
                entry['evaluations'].append({
                    'source':        row['source'],
                    'model':         row.get('model','?'),
                    'score':         int(row['score']) if pd.notna(row['score']) else -1,
                    'label':         row.get('label','?'),
                    'justification': str(row.get('justification',''))[:200]
                })
            pairs.append(entry)
            count += 1
            if count >= max_pairs:
                break
    return pairs


JUDGE_SYSTEM_PROMPT = """
Tu es un expert en évaluation de systèmes d'IA pour le recrutement.
On te donne des évaluations de la même paire (offre d'emploi × CV) par plusieurs modèles.
Tu dois analyser ces évaluations et déterminer :
1. Quel modèle produit les scores les plus réalistes et calibrés
2. Lequel est le plus cohérent et justifié
3. Un verdict global de fiabilité

Retourne UNIQUEMENT un JSON valide :
{
  "most_reliable": "<source du modèle le plus fiable>",
  "reasoning": "<2-3 phrases d'analyse>",
  "reliability_scores": {"<source>": <0-100>, ...},
  "verdict": "<1 phrase de conclusion>"
}
"""

def judge_comparison(pairs: list) -> dict:
    """Demande à Groq de juger quelle évaluation est la plus réaliste"""
    prompt = f"""
Voici {len(pairs)} paires Job × CV évaluées par différents modèles :

{json.dumps(pairs, indent=2, ensure_ascii=False)}

Analyse ces évaluations. Quel modèle est le plus réaliste et fiable ?
Retourne le JSON maintenant.
"""
    completion = _groq_client.chat.completions.create(
        model="qwen/qwen3-32b",
        messages=[
            {"role": "system", "content": JUDGE_SYSTEM_PROMPT},
            {"role": "user",   "content": prompt},
        ],
        max_tokens=800,
        temperature=0.2,
    )
    raw = completion.choices[0].message.content
