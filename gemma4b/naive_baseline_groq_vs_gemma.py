import json, re, requests, os
from datetime import datetime
from groq import Groq

# ── Prompt système partagé ────────────────────────────────────────────────────
SYSTEM_PROMPT = """
Tu es un recruteur expert.
Étant donné une offre d'emploi et un CV, évalue si le candidat est un bon match.
Retourne UNIQUEMENT un JSON valide, sans markdown ni backticks.

Structure exacte :
{
  "score": <entier de 0 à 100>,
  "label": "Strong Match" | "Good Fit" | "Moderate Match" | "Weak Match" | "Poor Match",
  "justification": "<exactement 2 phrases expliquant le verdict>"
}

Règles du label basées sur le score :
- 85-100 → Strong Match
- 70-84  → Good Fit
- 50-69  → Moderate Match
- 30-49  → Weak Match
- 0-29   → Poor Match
"""

GROQ_MODEL  = "llama-3.3-70b-versatile"
OLLAMA_URL  = "http://localhost:11434/api/chat"


def build_user_prompt(cv_text: str, job_text: str) -> str:
    return (
        f"OFFRE D'EMPLOI :\n---\n{str(job_text).strip()}\n\n"
        f"CV DU CANDIDAT :\n---\n{str(cv_text).strip()}\n\n"
        "Retourne le JSON maintenant."
    )

# ── Parsing robuste du JSON ───────────────────────────────────────────────────
def parse_json(raw: str) -> dict:
    clean = re.sub(r'```json|```', '', raw).strip()
    m = re.search(r'\{.*\}', clean, re.DOTALL)
    if m:
        return json.loads(m.group())
    raise ValueError(f'JSON introuvable dans : {raw[:300]}')

# ── Recalcul défensif du label à partir du score ─────────────────────────────
def score_to_label(score: int) -> str:
    if score >= 85: return 'Strong Match'
    if score >= 70: return 'Good Fit'
    if score >= 50: return 'Moderate Match'
    if score >= 30: return 'Weak Match'
    return 'Poor Match'


def run_matching_ollama(cv_text, job_text, job_idx, cv_col, temperature=0.1):
    """Appel Ollama local — gemma3:latest"""
    payload = {
        "model": builtins.OLLAMA_MODEL,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user",   "content": build_user_prompt(cv_text, job_text)},
        ],
        "stream": False,
        "options": {"temperature": temperature, "num_predict": 400}
    }
    resp = requests.post(OLLAMA_URL, json=payload, timeout=180)
    resp.raise_for_status()
    raw = resp.json()["message"]["content"]

    r = parse_json(raw)
    r['score']         = int(r.get('score', 0))
    r['label']         = r.get('label', score_to_label(r['score']))
    r['label_checked'] = score_to_label(r['score'])
    r['job_idx']       = int(job_idx)
    r['cv_col']        = cv_col
    r['model']         = builtins.OLLAMA_MODEL
    r['source']        = 'ollama'
    r['generated_at']  = datetime.now().isoformat()
    return r


_groq_client = Groq(api_key=os.environ['GROQ_API_KEY'])

def run_matching_groq(cv_text, job_text, job_idx, cv_col, temperature=0.1):
    """Appel Groq API — llama-3.3-70b-versatile (juge externe)"""
    completion = _groq_client.chat.completions.create(
        model=GROQ_MODEL,
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user",   "content": build_user_prompt(cv_text, job_text)},
        ],
        max_tokens=400,
        temperature=temperature,
    )
    raw = completion.choices[0].message.content

    r = parse_json(raw)
    r['score']         = int(r.get('score', 0))
    r['label']         = r.get('label', score_to_label(r['score']))
    r['label_checked'] = score_to_label(r['score'])
    r['job_idx']       = int(job_idx)
    r['cv_col']        = cv_col
    r['model']         = GROQ_MODEL
    r['source']        = 'groq'
    r['generated_at']  = datetime.now().isoformat()
    return r

