"""## ═══ BLOC 10 — 🔍 Normalisation des rapports Gemma4b ═══

Extraction des champs clés (`score`, `label`, `justification`) depuis la structure du rapport Gemma4b (format `overall_assessment` ou format baseline).
"""

import pandas as pd

def extract_report_fields(report: dict) -> dict:
    """
    Extrait les champs score/label/justification depuis différents formats de rapport :
    - Format pipeline Gemma (overall_assessment, match_pct, verdict)
    - Format baseline simple (score, label, justification)
    """
    out = {
        'job_idx':       report.get('job_idx', report.get('job_id', '?')),
        'cv_col':        report.get('cv_col',  report.get('cv_id',  '?')),
        'source':        'gemma4b_zip',
        'model':         report.get('model', 'gemma3:4b'),
        '_source_file':  report.get('_source_file', ''),
    }

    # ── Format pipeline (overall_assessment) ──────────────────────────────────
    oa = report.get('overall_assessment', {})
    if oa:
        match_pct = oa.get('match_pct', oa.get('match_percentage', None))
        verdict   = oa.get('verdict', oa.get('label', None))
        rationale = oa.get('rationale', oa.get('justification', ''))
        if match_pct is not None:
            out['score']         = int(float(str(match_pct).replace('%','').strip()))
            out['label']         = verdict or score_to_label(out['score'])
            out['justification'] = str(rationale)[:300]
            out['label_checked'] = score_to_label(out['score'])
            return out

    # ── Format baseline simple ─────────────────────────────────────────────────
    score = report.get('score', None)
    if score is not None:
        out['score']         = int(float(score))
        out['label']         = report.get('label', score_to_label(out['score']))
        out['justification'] = str(report.get('justification', ''))[:300]
        out['label_checked'] = score_to_label(out['score'])
        return out

    # ── Format scoring_results ─────────────────────────────────────────────────
    sr = report.get('scoring_results', report.get('phase3', {}))
    if sr:
        sc = sr.get('final_score', sr.get('score', None))
        if sc is not None:
            out['score']         = int(float(sc))
            out['label']         = sr.get('label', score_to_label(out['score']))
            out['justification'] = str(sr.get('summary', sr.get('justification', '')))[:300]
            out['label_checked'] = score_to_label(out['score'])
            return out

    # ── Fallback — pas de score reconnaissable ─────────────────────────────────
    out['score']         = -1
    out['label']         = 'N/A'
    out['justification'] = 'Format non reconnu — clés : ' + ', '.join(report.keys())[:200]
    out['label_checked'] = 'N/A'
    return out


